import { test, expect } from '../../fixtures';
import { nitLanguages } from '../../utils/nitData';

test.describe('Language and script switcher', () => {
  test('defaults to Bosnian', async ({ nitHome }) => {
    await nitHome.goto();

    expect(await nitHome.htmlLang()).toBe('bs');
    await expect(nitHome.navLink('Usluge')).toBeVisible();
  });

  // Data-driven: every language translates the page and sets <html lang>
  for (const lang of nitLanguages.filter((l) => l.code !== 'bs')) {
    test(`switches to ${lang.button}`, async ({ nitHome }) => {
      await nitHome.goto();

      await nitHome.chooseLanguage(lang.button);

      await expect(nitHome.heading).toHaveAccessibleName(lang.h1);
      await expect.poll(() => nitHome.htmlLang()).toBe(lang.htmlLang);
      // The menu closes after a choice, so its buttons are hidden – include them explicitly
      const chosen = nitHome.languageMenu.getByRole('button', { name: lang.button, includeHidden: true });
      await expect(chosen).toHaveAttribute('aria-pressed', 'true');
    });
  }

  test('remembers the chosen language after a reload', async ({ page, nitHome }) => {
    await nitHome.goto();
    await nitHome.chooseLanguage('Deutsch');

    await page.reload();

    await expect(nitHome.heading).toHaveAccessibleName('Vom ersten Klick bis zum fertigen Ergebnis.');
  });

  test('can be preselected with the ?lang= URL parameter', async ({ nitHome }) => {
    await nitHome.goto('?lang=en');

    await expect(nitHome.heading).toHaveAccessibleName('From the first click to the job done.');
    await expect(nitHome.navLink('Services')).toBeVisible();
  });

  test('translates the interactive tools too, not only static text', async ({ page, nitHome }) => {
    await nitHome.goto('?lang=de');

    // Tab labels are generated by JavaScript after load, so they test the runtime translation
    await expect(page.getByRole('tab', { selected: true })).toHaveAccessibleName('01 Fertigungskalkulation');
  });

  test('language menu button announces the current language', async ({ nitHome }) => {
    // Accessibility: the toggle is only a flag image, so its aria-label must say
    // what it is and which language is active – in that language.
    await nitHome.goto();
    await expect(nitHome.languageToggle).toHaveAccessibleName('Jezik i pismo: Bosanski');

    await nitHome.chooseLanguage('English');
    await expect(nitHome.languageToggle).toHaveAccessibleName('Language and script: English');
  });
});
